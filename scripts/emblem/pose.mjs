// 金翼羅盤（第二版）：收攏姿態的參數。
// 依據 docs/06_research-and-design/proposals/emblem/BRIEF.md §3、§7。
//
// 這個檔案只描述「雙翼收攏時，每根羽毛指向哪個角度」，不含任何幾何；geometry.mjs 只讀取。
//
// 角度的定義（以左翼為準，右翼是鏡射）：
//   0   = 由羽毛的基部水平指向外側（左）
//   正值 = 向上抬
//   -90 = 垂直朝下；小於 -90 = 朝下並略向內（靠向中軸）
//
// 形狀：POSE.tiers[t][i] 是第 t 層（0 飛羽、1 中羽、2 覆羽）第 i 根羽毛收攏後的角度（度）。
// i 與 geometry.mjs 的 TIERS[t].feathers[i] 一一對應：i = 0 是展開時最上面的一根（基部在腕點）。
// 數量必須與 TIERS 相同（13／11／10）。同一層的角度要單調，羽毛才不會在收攏途中交錯。
//
// 第二版每根羽毛繞「自己的基部」旋轉（基部都在翼臂上，位置不動）：
//   旋轉角度 = (收攏角度 − 展開角度) × (1 − open)

/** 等距的一把扇子：由 first 開始，每根差 step 度，共 count 根。 */
export function fan(first, step, count) {
  return Array.from({ length: count }, (_, i) => first + step * i);
}

// 收攏的樣子：羽毛全部垂下，貼在羅盤兩側，像闔起的翅膀。
// 基部沿翼臂由外上（腕點）排到內下（翼根），所以外側的羽毛掛得高、內側的掛得低。
// 外側的向內收（小於 -90），內側的略向外，羽尖往同一處收攏，整束由上往下收窄。
export const POSE = {
  tiers: [
    fan(-103, 1.4, 13), // 飛羽：-103 … -86.2
    fan(-104, 1.5, 11), // 中羽：-104 … -89
    fan(-106, 1.6, 10), // 覆羽：-106 … -91.6
  ],
};
